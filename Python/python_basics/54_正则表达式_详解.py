# 2.2 日志解析示例（重点）
# --------------------------------------------

print("2.2 日志解析示例")
print("-" * 60)

# 模拟日志行
log_line = "2024-05-31 14:23:45 [ERROR] Database connection failed: timeout"

# 日志格式：日期 时间 [级别] 消息
# 正则表达式解析
pattern = r'(\d{4}-\d{2}-\d{2}) (\d{2}:\d{2}:\d{2}) \[(\w+)\] (.+)'
match = re.match(pattern, log_line)

if match:
    date = match.group(1)      # 第1个分组：日期
    time = match.group(2)      # 第2个分组：时间
    level = match.group(3)     # 第3个分组：级别
    message = match.group(4)   # 第4个分组：消息

    print(f"日期：{date}")
    print(f"时间：{time}")
    print(f"级别：{level}")
    print(f"消息：{message}")

print()


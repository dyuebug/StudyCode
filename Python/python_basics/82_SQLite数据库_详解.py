print("""
【游标】Cursor

什么是游标？
- 游标 = 数据库操作的"遥控器"
- 通过游标执行 SQL、获取结果
- 一个连接可以创建多个游标

类比：
- 连接（Connection）= 打开数据库大门
- 游标（Cursor）= 进门后的操作工具

创建游标：
cursor = conn.cursor()

游标的作用：
1. 执行 SQL：cursor.execute(sql)
2. 获取结果：cursor.fetchall()
3. 批量操作：cursor.executemany()

Connection vs Cursor：
┌──────────────┬────────────────────────┐
│ Connection   │ Cursor                 │
├──────────────┼────────────────────────┤
│ 连接数据库   │ 执行SQL                │
│ 管理事务     │ 获取结果               │
│ commit()     │ execute()              │
│ close()      │ fetchall()             │
└──────────────┴────────────────────────┘
""")

# 示例3：创建游标
print("示例3：创建游标")
conn = sqlite3.connect('test.db')
cursor = conn.cursor()
print(f"✅ 游标创建成功：{cursor}")

# 关闭（先关游标，再关连接）
cursor.close()
conn.close()
print("   游标和连接已关闭")


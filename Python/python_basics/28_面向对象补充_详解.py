class PasswordChecker:
    """密码检测器：演示私有方法只给类内部用"""

    def __init__(self, password):
        self.__password = password

    def __has_min_length(self):
        """私有方法：只在类内部检查长度"""
        return len(self.__password) >= 8

    def check_password(self):
        """公开方法：统一对外提供检查结果"""
        if self.__has_min_length():
            print("密码长度合格。")
        else:
            print("密码太短，不合格。")

checker1 = PasswordChecker("123456")
checker2 = PasswordChecker("abc123456")
checker1.check_password()
checker2.check_password()


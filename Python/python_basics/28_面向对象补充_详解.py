class Student:
    """带封装思想的学生类"""

    def __init__(self, name, score):
        self.name = name
        # 私有属性：不希望外部直接乱改
        self.__score = score

    def get_score(self):
        """公开方法：安全读取成绩"""
        return self.__score

    def set_score(self, new_score):
        """公开方法：安全修改成绩"""
        # 先做数据校验，再决定是否修改
        if 0 <= new_score <= 100:
            self.__score = new_score
            print(f"{self.name} 的成绩已更新为 {self.__score}")
        else:
            print("成绩必须在 0 到 100 之间，修改失败。")

student = Student("小红", 88)
print(f"当前成绩：{student.get_score()}")
student.set_score(92)
print(f"修改后成绩：{student.get_score()}")
student.set_score(-50)  # 非法数据
print(f"非法修改后成绩仍然是：{student.get_score()}")


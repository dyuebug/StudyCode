/*
 * hanzi_font.c —— 16x16 汉字点阵数据（"百问网"）
 *
 * 数据逐字节抄自《HAL快速入门与项目实战(基于DshanMCU-103)》第 8.5.4 节。
 * 为什么拆成独立文件而不是像 ascii_font.c 那样被 #include 进驱动：
 *   1) 没有 HAL 依赖，主机端渲染程序可以直接编译它做位序验证；
 *   2) 单独编译进固件，避免同一份数据在两个翻译单元里各存一份。
 * 与 ascii_font.c 的相同点是"数据与代码分离"，不同点是链接方式。
 */
#include "hanzi_font.h"

const hanzi16_t g_hanzi16[] = {
    /* "百" */
    { 0x767E,
      { 0x02, 0x02, 0xE2, 0x22, 0x22, 0x32, 0x2A, 0x26,
        0x22, 0x22, 0x22, 0x22, 0xE2, 0x02, 0x02, 0x00 },
      { 0x00, 0x00, 0xFF, 0x42, 0x42, 0x42, 0x42, 0x42,
        0x42, 0x42, 0x42, 0x42, 0xFF, 0x00, 0x00, 0x00 } },

    /* "问" */
    { 0x95EE,
      { 0x00, 0xF8, 0x01, 0x02, 0x00, 0xE2, 0x22, 0x22,
        0x22, 0xE2, 0x02, 0x02, 0x02, 0xFE, 0x00, 0x00 },
      { 0x00, 0xFF, 0x00, 0x00, 0x00, 0x1F, 0x08, 0x08,
        0x08, 0x1F, 0x00, 0x40, 0x80, 0x7F, 0x00, 0x00 } },

    /* "网" */
    { 0x7F51,
      { 0x00, 0xFE, 0x02, 0x22, 0x42, 0x82, 0x72, 0x02,
        0x22, 0x42, 0x82, 0x72, 0x02, 0xFE, 0x00, 0x00 },
      { 0x00, 0xFF, 0x10, 0x08, 0x06, 0x01, 0x0E, 0x10,
        0x08, 0x06, 0x01, 0x4E, 0x80, 0x7F, 0x00, 0x00 } },
};

const unsigned g_hanzi16_count = sizeof(g_hanzi16) / sizeof(g_hanzi16[0]);

const hanzi16_t *Hanzi16_Find(uint16_t code)
{
    unsigned i;
    for (i = 0; i < g_hanzi16_count; i++) {
        if (g_hanzi16[i].code == code)
            return &g_hanzi16[i];
    }
    return 0;
}

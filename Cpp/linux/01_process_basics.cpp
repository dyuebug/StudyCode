void showDeepDive() {
    cout << R"(
============================================================
🔍 深入理解：写时复制（COW - Copy on Write）（选学）
============================================================

fork()后，父子进程共享同一份物理内存页，页表标记为"只读"。

当任一进程尝试写入：
  1. CPU触发"写保护"缺页异常
  2. 内核复制该内存页（仅复制被写的页，不是全部）
  3. 修改子进程页表，指向新复制的页
  4. 修改两个进程的该页为"可写"
  5. 写操作继续执行

好处：
  - fork()极快（只复制页表，不复制数据）
  - 如果子进程立即exec()，数据页根本不需要复制
  - 节省内存，特别是 fork 后立即 exec 的场景（vfork优化）

============================================================
)";
}


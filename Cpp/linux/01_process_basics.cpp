/*
【核心概念】

是什么？
- 进程（Process）：运行中的程序实例，有独立的地址空间
- fork()：复制当前进程，创建子进程（调用一次，返回两次）
- exec()：用新程序替换当前进程映像（不创建新进程）
- wait()：父进程等待子进程结束，回收资源

为什么需要？
- 多任务并发：同时运行多个任务
- 隔离性：子进程崩溃不影响父进程
- Shell原理：shell用fork+exec来运行命令

核心特点：
- fork后父子进程代码段共享，数据段写时复制（COW）
- exec后进程映像完全替换，但PID不变
- 子进程结束后变为"僵尸"，直到父进程wait()回收
*/


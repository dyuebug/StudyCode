void showMistakes() {
    cout << R"(
============================================================
常见错误和陷阱 ⭐⭐⭐⭐⭐
============================================================

❌ 错误1：忘记判断fork()返回值
  fork();  // ❌ 不判断返回值，父子进程都执行相同代码
  // ✅ 必须用 if(pid==0)/else 区分父子进程

❌ 错误2：子进程结束用return而非exit()
  if (pid == 0) {
      doWork();
      return 0;  // ❌ 可能调用父进程注册的atexit()函数，引发双重清理
  }
  // ✅ 子进程必须用 exit() 或 _exit() 结束

❌ 错误3：父进程不调用wait()导致僵尸进程
  fork();  // 子进程结束后变僵尸，永远残留
  // ✅ 父进程必须调用wait()/waitpid()
  // ✅ 或设置 signal(SIGCHLD, SIG_IGN) 让内核自动回收

❌ 错误4：fork()后对cout的缓冲区重复输出
  cout << "hello";  // 缓冲区有数据
  fork();           // 父子进程各自有一份缓冲区 → 输出两次"hello"
  // ✅ fork()前调用 fflush(stdout) 刷新缓冲区

❌ 错误5：exec()后继续使用fork()前打开的文件
  int fd = open("file", O_RDWR);
  fork();
  execl("/bin/prog", ...);  // fd被子进程继承
  // ✅ 对不需要继承的fd设置 fcntl(fd, F_SETFD, FD_CLOEXEC)

============================================================
)";
}


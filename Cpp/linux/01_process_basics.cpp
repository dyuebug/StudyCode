void showForkExample() {
    cout << R"(
------------------------------------------------------------
fork() 基础用法
------------------------------------------------------------

// ---- 真实Linux代码 ----
#include <unistd.h>
#include <sys/wait.h>

int main() {
    pid_t pid = fork();

    if (pid < 0) {
        perror("fork失败");
        return 1;
    }

    if (pid == 0) {
        // ★ 子进程执行这里（pid==0）
        cout << "子进程 PID=" << getpid()
             << " 父PID=" << getppid() << endl;
        sleep(1);
        exit(42);  // 退出码42
    } else {
        // ★ 父进程执行这里（pid==子进程PID）
        cout << "父进程 PID=" << getpid()
             << " 子进程PID=" << pid << endl;

        int status;
        waitpid(pid, &status, 0);  // 等待子进程结束

        if (WIFEXITED(status))
            cout << "子进程退出码=" << WEXITSTATUS(status) << endl;
    }
    return 0;
}

// 输出：
// 父进程 PID=1234 子进程PID=1235
// 子进程 PID=1235 父PID=1234
// 子进程退出码=42
)";
}

void showExecExample() {
    cout << R"(
------------------------------------------------------------
fork + exec：Shell 运行命令的原理
------------------------------------------------------------

// ---- 真实Linux代码 ----
#include <unistd.h>
#include <sys/wait.h>

int main() {
    pid_t pid = fork();

    if (pid == 0) {
        // 子进程：用 ls -l 替换自身
        execl("/bin/ls", "ls", "-l", "/tmp", nullptr);
        // exec成功后，下面代码不会执行
        perror("exec失败");
        exit(1);
    }

    // 父进程等待
    int status;
    wait(&status);
    cout << "ls命令执行完毕" << endl;
    return 0;
}

// exec函数族：
// execl  (路径, arg0, arg1, ..., NULL)     → 可变参数列表
// execv  (路径, char* argv[])              → 参数数组
// execle (路径, ..., NULL, char* envp[])  → 自定义环境变量
// execvp (文件名, argv[])                 → 在PATH中搜索
)";
}


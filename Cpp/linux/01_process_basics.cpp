void showConcepts() {
    cout << R"(
============================================================
Linux 进程模型 - 核心概念
============================================================

【进程 vs 线程】
  进程：独立地址空间，资源隔离，开销大
  线程：共享地址空间，资源共享，开销小
  嵌入式FreeRTOS的"任务" ≈ Linux的"线程"

【fork() - 复制进程】

  pid_t pid = fork();

  返回值含义：
  ┌─────────────────────────────────────────┐
  │  fork() 调用一次，返回两次              │
  │                                         │
  │  父进程：返回子进程的PID（> 0）         │
  │  子进程：返回 0                         │
  │  失败：返回 -1（内存不足等）            │
  └─────────────────────────────────────────┘

  fork后内存状态：
  - 代码段（.text）：父子共享（只读，无需复制）
  - 数据段（.data/.bss）：写时复制（COW）
    → 子进程修改变量时，内核才真正复制该页
  - 文件描述符：父子共享同一张fd表的副本

【exec() - 替换进程映像】

  execl("/bin/ls", "ls", "-l", nullptr);

  - 替换当前进程的代码/数据/堆/栈
  - PID不变，但程序完全替换
  - exec成功后，后面的代码不再执行
  - 打开的fd默认继承（除非设置FD_CLOEXEC）

【wait() - 回收子进程】

  int status;
  pid_t child = wait(&status);         // 等待任意子进程
  pid_t child = waitpid(pid, &s, 0);  // 等待指定子进程

  WIFEXITED(status)   → 是否正常退出
  WEXITSTATUS(status) → 退出码（0~255）
  WIFSIGNALED(status) → 是否被信号终止
  WTERMSIG(status)    → 终止信号编号

【僵尸进程（Zombie）】
  子进程已结束，但父进程未调用wait() → 进程表中残留条目
  危害：占用PID资源，大量僵尸进程导致无法创建新进程
  预防：父进程及时调用wait()，或忽略SIGCHLD信号

============================================================
)";
}


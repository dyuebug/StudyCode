/*
【核心概念】

是什么？
- 管道（Pipe）：内核维护的字节流缓冲区，用于进程间传递数据
- 匿名管道：只能用于有亲缘关系的进程（父子/兄弟）
- 命名管道（FIFO）：文件系统中的特殊文件，任意进程均可使用

为什么需要？
- 进程地址空间隔离，不能直接共享内存
- 管道是最简单的IPC机制，shell的 | 就是匿名管道

核心特点：
- 单向：数据从写端流向读端（双向需两个管道）
- 阻塞：读端无数据时阻塞；写端缓冲满时阻塞
- 关闭写端：读端读完后得到 EOF（read返回0）
- 关闭读端：写端写入时收到 SIGPIPE 信号
*/


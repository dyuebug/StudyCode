void showAnonymousPipe() {
    cout << R"(
------------------------------------------------------------
匿名管道：父写子读
------------------------------------------------------------

// ---- 真实Linux代码 ----
#include <unistd.h>
#include <sys/wait.h>
#include <cstring>

int main() {
    int fd[2];
    pipe(fd);  // 创建管道

    pid_t pid = fork();

    if (pid == 0) {
        // 子进程：读数据
        close(fd[1]);           // ★ 关闭写端（子进程不写）
        char buf[64] = {};
        read(fd[0], buf, sizeof(buf));
        cout << "子进程收到: " << buf << endl;
        close(fd[0]);
        exit(0);
    } else {
        // 父进程：写数据
        close(fd[0]);           // ★ 关闭读端（父进程不读）
        const char* msg = "Hello from parent!";
        write(fd[1], msg, strlen(msg));
        close(fd[1]);           // ★ 关闭写端，子进程read()得到EOF
        wait(nullptr);
    }
    return 0;
}
)";
}

void showBidirectionalPipe() {
    cout << R"(
------------------------------------------------------------
双向通信：两个管道
------------------------------------------------------------

// ---- 真实Linux代码 ----
int p2c[2], c2p[2];  // parent→child，child→parent
pipe(p2c);
pipe(c2p);

if (fork() == 0) {
    // 子进程
    close(p2c[1]); close(c2p[0]);  // 关闭不用的端

    char buf[64];
    read(p2c[0], buf, sizeof(buf));    // 从父进程读
    cout << "子进程收到: " << buf << endl;

    write(c2p[1], "done", 4);         // 回复父进程
    exit(0);
} else {
    // 父进程
    close(p2c[0]); close(c2p[1]);

    write(p2c[1], "task", 4);         // 发任务给子进程

    char buf[64] = {};
    read(c2p[0], buf, sizeof(buf));   // 等待子进程回复
    cout << "父进程收到回复: " << buf << endl;
    wait(nullptr);
}
)";
}

void showFIFO() {
    cout << R"(
------------------------------------------------------------
命名管道（FIFO）：无亲缘关系进程通信
------------------------------------------------------------

// ---- 进程A（写者）----
#include <fcntl.h>
#include <sys/stat.h>

mkfifo("/tmp/myfifo", 0666);   // 创建FIFO（已存在则忽略）
int fd = open("/tmp/myfifo", O_WRONLY);  // 阻塞直到读者打开
write(fd, "hello", 5);
close(fd);

// ---- 进程B（读者）----
int fd = open("/tmp/myfifo", O_RDONLY);  // 阻塞直到写者打开
char buf[64] = {};
read(fd, buf, sizeof(buf));
cout << "收到: " << buf << endl;
close(fd);
unlink("/tmp/myfifo");  // 删除FIFO文件

// 典型使用场景：
// - 日志收集：多个进程写同一FIFO，日志进程读取
// - 简单消息总线：替代复杂IPC机制
)";
}


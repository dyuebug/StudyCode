void showConcepts() {
    cout << R"(
============================================================
管道（Pipe）核心概念
============================================================

【匿名管道结构】

  父进程                        子进程
  ┌──────────┐                 ┌──────────┐
  │ fd[1]写端├──→ 内核缓冲区 ──→│ fd[0]读端│
  └──────────┘   （最大64KB）   └──────────┘

  int fd[2];
  pipe(fd);   // fd[0]=读端  fd[1]=写端

  重要规则：
  - 父进程写，必须关闭自己的 fd[0]（读端）
  - 子进程读，必须关闭自己的 fd[1]（写端）
  - 不关闭多余的端 → read() 永远不会得到 EOF

【pipe() 函数卡片】

  #include <unistd.h>
  int pipe(int fd[2]);

  参数：fd[2] — 输出参数，fd[0]=读端，fd[1]=写端
  返回：0=成功，-1=失败（设置errno）
  读写：read(fd[0], buf, size) / write(fd[1], buf, size)

【命名管道（FIFO）】

  mkfifo("/tmp/myfifo", 0666);  // 创建FIFO文件

  进程A（写）：int fd = open("/tmp/myfifo", O_WRONLY);
  进程B（读）：int fd = open("/tmp/myfifo", O_RDONLY);

  特点：
  - open() 默认阻塞，直到两端都打开
  - 数据不持久化（关闭后数据消失）
  - 文件系统中可见（ls -l 显示 p 类型）

============================================================
)";
}


void showDeepDive() {
    cout << R"(
============================================================
🔍 深入理解：管道的阻塞与缓冲（选学）
============================================================

管道内核缓冲区（Linux默认64KB）：

写操作：
  write(fd[1], data, n)
  → n <= 缓冲剩余空间：立即写入，返回n
  → n > 缓冲剩余空间：阻塞，直到读者取走数据腾出空间
  → 读端已关闭：收到SIGPIPE，write返回-1，errno=EPIPE

读操作：
  read(fd[0], buf, n)
  → 缓冲有数据：立即返回（最多n字节）
  → 缓冲空且写端未关闭：阻塞等待
  → 缓冲空且写端已关闭：返回0（EOF）

原子写（PIPE_BUF = 4096字节）：
  写入 <= PIPE_BUF 字节时，内核保证原子性（不会与其他写者交错）
  写入 > PIPE_BUF 字节时，可能与其他写者数据交错

============================================================
)";
}


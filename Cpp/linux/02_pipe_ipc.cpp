void showMistakes() {
    cout << R"(
============================================================
常见错误和陷阱 ⭐⭐⭐⭐⭐
============================================================

❌ 错误1：不关闭多余的管道端
  pipe(fd);
  fork();
  // 子进程只读，但不关闭fd[1]（写端）
  read(fd[0], buf, n);  // ❌ 永远阻塞！因为写端（子进程自己的）还开着
  // ✅ fork后立即关闭不需要的端

❌ 错误2：父进程先写再wait，导致死锁
  write(fd[1], big_data, 100000);  // ❌ 数据>64KB，缓冲满，父进程阻塞
  wait(nullptr);                   // 永远到不了这里
  // 子进程也在等待...死锁！
  // ✅ 先fork，子进程读，父进程写；或用select/非阻塞IO

❌ 错误3：忘记处理SIGPIPE
  // 读端关闭后，写端write()收到SIGPIPE，默认终止进程
  // ✅ signal(SIGPIPE, SIG_IGN) 忽略，用errno=EPIPE判断

❌ 错误4：把管道当消息边界使用
  write(fd[1], "msg1", 4);  write(fd[1], "msg2", 4);
  read(fd[0], buf, 8);  // 可能一次读到"msg1msg2"，也可能分两次
  // ✅ 管道是字节流，无消息边界；需要自己实现分帧（如长度前缀）

❌ 错误5：FIFO的open()阻塞未处理
  open("/tmp/fifo", O_RDONLY);  // 若无写者，永久阻塞
  // ✅ 用 O_RDONLY|O_NONBLOCK 非阻塞打开，或确保两端都已就绪

============================================================
)";
}


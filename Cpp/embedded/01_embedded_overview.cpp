// 3.3 volatile 关键字（硬件寄存器访问）⭐⭐⭐⭐⭐
// --------------------------------------------

/*
【volatile 是什么？】
- volatile 告诉编译器：这个变量可能在程序控制之外被修改
- 禁止编译器对该变量进行优化（不缓存到寄存器）
- 每次访问都必须从内存中读取

【为什么嵌入式需要 volatile？】

场景1：硬件寄存器
- 硬件可能随时改变寄存器的值（如 ADC 采样完成）
- 如果不用 volatile，编译器可能缓存旧值，读不到最新值

场景2：中断服务程序（ISR）
- 中断可能随时修改某个变量
- 主程序需要读到最新值

场景3：多线程共享变量
- 其他线程可能修改变量
- 需要每次都从内存读取

【示例】
*/

// 模拟硬件寄存器（实际嵌入式中是固定内存地址）
volatile uint32_t GPIOA_IDR = 0;  // GPIO 输入数据寄存器（硬件会修改它）
volatile uint32_t ADC_DR = 0;     // ADC 数据寄存器（ADC 完成后硬件写入）

void demo_volatile()
{
    cout << "\n=== volatile 关键字演示 ===" << endl;

    // ❌ 错误示例（不用 volatile）
    // uint32_t sensor_value = ADC_DR;  // 编译器可能优化，只读一次
    // while (sensor_value == 0) {      // 可能永远循环，因为读的是缓存值
    //     // 等待 ADC 完成
    // }

    // ✅ 正确示例（用 volatile）
    // volatile uint32_t* adc_reg = &ADC_DR;
    // while (*adc_reg == 0) {  // 每次循环都从内存读取最新值
    //     // 等待 ADC 完成
    // }

    cout << "volatile 关键字确保每次都从内存读取最新值" << endl;
    cout << "对于硬件寄存器，必须使用 volatile！" << endl;

    // 模拟读取 GPIO 输入
    // 在真实嵌入式中，GPIOA_IDR 的地址是固定的（如 0x40020010）
    // 硬件会根据引脚状态自动更新这个寄存器的值
    uint32_t pin_state = (GPIOA_IDR >> 0) & 1;  // 读取 PA0 的状态
    cout << "PA0 输入状态：" << pin_state << endl;
}


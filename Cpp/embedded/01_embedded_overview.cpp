// --------------------------------------------
// 3.2 位操作（嵌入式核心技能）⭐⭐⭐⭐⭐
// --------------------------------------------

/*
【为什么嵌入式需要位操作？】

嵌入式系统通过"寄存器"控制硬件。
寄存器是一个 32 位（或 8/16 位）的内存地址，
每一位（bit）控制不同的硬件功能。

例如：GPIO 控制寄存器（假设地址 0x40020000）
- Bit 0：控制 PA0 引脚输出（0=低电平，1=高电平）
- Bit 1：控制 PA1 引脚输出
- Bit 2：控制 PA2 引脚输出
- ...

要控制某个引脚，必须精确地设置某一位，
而不影响其他位。这就需要位操作。

【常用位操作】
- 置位（Set bit）：将某位设为 1
  reg |= (1 << n);    // 将第 n 位置 1

- 清位（Clear bit）：将某位设为 0
  reg &= ~(1 << n);   // 将第 n 位清 0

- 翻转（Toggle bit）：将某位取反
  reg ^= (1 << n);    // 将第 n 位翻转

- 读位（Read bit）：读取某位的值
  bool bit = (reg >> n) & 1;  // 读取第 n 位
*/

void demo_bit_operations()
{
    cout << "\n=== 位操作演示 ===" << endl;

    // 模拟一个 GPIO 输出寄存器（32位）
    // 每一位控制一个引脚的输出状态
    uint32_t gpio_output_register = 0x00000000;  // 初始全部为低电平

    cout << "初始状态：0x" << hex << gpio_output_register << dec << endl;

    // ----------------------------------------
    // 置位操作：将 PA5（第5位）设为高电平（点亮 LED）
    // ----------------------------------------
    // 方法：reg |= (1 << n)
    // 原理：1 << 5 = 0b00100000 = 0x20
    //       与原值 OR，只改变第5位，其他位不变
    gpio_output_register |= (1 << 5);
    cout << "PA5 置高后：0x" << hex << gpio_output_register << dec
         << "（PA5 = " << ((gpio_output_register >> 5) & 1) << "）" << endl;

    // ----------------------------------------
    // 置位操作：同时将 PA3 也设为高电平
    // ----------------------------------------
    gpio_output_register |= (1 << 3);
    cout << "PA3 置高后：0x" << hex << gpio_output_register << dec << endl;

    // ----------------------------------------
    // 清位操作：将 PA5 设为低电平（熄灭 LED）
    // ----------------------------------------
    // 方法：reg &= ~(1 << n)
    // 原理：~(1 << 5) = 0b11011111
    //       与原值 AND，只清除第5位，其他位不变
    gpio_output_register &= ~(1 << 5);
    cout << "PA5 清低后：0x" << hex << gpio_output_register << dec
         << "（PA5 = " << ((gpio_output_register >> 5) & 1) << "）" << endl;

    // ----------------------------------------
    // 翻转操作：翻转 PA3 的状态
    // ----------------------------------------
    // 方法：reg ^= (1 << n)
    gpio_output_register ^= (1 << 3);
    cout << "PA3 翻转后：0x" << hex << gpio_output_register << dec
         << "（PA3 = " << ((gpio_output_register >> 3) & 1) << "）" << endl;

    // ----------------------------------------
    // 读位操作：读取 PA3 的当前状态
    // ----------------------------------------
    bool pa3_state = (gpio_output_register >> 3) & 1;
    cout << "PA3 当前状态：" << pa3_state << endl;

    // ----------------------------------------
    // 实用宏定义（嵌入式常用写法）
    // ----------------------------------------
    cout << "\n--- 使用宏定义简化位操作 ---" << endl;

    // 定义常用位操作宏
    #define SET_BIT(reg, bit)    ((reg) |= (1U << (bit)))
    #define CLEAR_BIT(reg, bit)  ((reg) &= ~(1U << (bit)))
    #define TOGGLE_BIT(reg, bit) ((reg) ^= (1U << (bit)))
    #define READ_BIT(reg, bit)   (((reg) >> (bit)) & 1U)

    uint32_t reg = 0;
    SET_BIT(reg, 7);    // 置位第7位
    cout << "SET_BIT(reg, 7)：0x" << hex << reg << dec << endl;

    CLEAR_BIT(reg, 7);  // 清位第7位
    cout << "CLEAR_BIT(reg, 7)：0x" << hex << reg << dec << endl;
}


/*
────────────────────────────────────────────
4.1 嵌入式内存布局
────────────────────────────────────────────

【STM32F103 内存布局（典型示例）】

Flash（程序存储器，128KB）：
┌─────────────────────────────┐ 0x0800_0000
│  中断向量表（Interrupt Vector Table）│
├─────────────────────────────┤
│  代码段（.text）             │
│  - 函数代码                  │
│  - 常量字符串                │
├─────────────────────────────┤
│  只读数据段（.rodata）        │
│  - const 变量                │
└─────────────────────────────┘ 0x0802_0000

RAM（数据存储器，20KB）：
┌─────────────────────────────┐ 0x2000_0000
│  数据段（.data）             │
│  - 已初始化的全局变量         │
├─────────────────────────────┤
│  BSS 段（.bss）              │
│  - 未初始化的全局变量（清零） │
├─────────────────────────────┤
│  堆（Heap）↓                 │
│  - 动态分配的内存（new/malloc）│
│  - 嵌入式中尽量避免使用       │
├─────────────────────────────┤
│  空闲区域                    │
├─────────────────────────────┤
│  栈（Stack）↑                │
│  - 局部变量                  │
│  - 函数调用信息               │
└─────────────────────────────┘ 0x2000_5000

【关键点】
1. Flash 存放程序代码（掉电不丢失）
2. RAM 存放运行时数据（掉电丢失）
3. 嵌入式中 RAM 非常有限，要节省使用
4. 尽量避免动态内存分配（堆）
5. 注意栈溢出（Stack Overflow）问题
*/

void demo_memory_model()
{
    cout << "\n=== 嵌入式内存模型演示 ===" << endl;

    // 全局变量（存放在 .data 或 .bss 段）
    static uint32_t global_counter = 0;  // .data 段（已初始化）
    static uint8_t  buffer[64];          // .bss 段（未初始化，自动清零）

    // 局部变量（存放在栈上）
    uint8_t local_var = 42;              // 栈上，函数返回后释放

    // 嵌入式中避免动态内存分配
    // ❌ 不推荐：
    // uint8_t* dynamic_buf = new uint8_t[64];  // 堆分配，可能导致碎片化

    // ✅ 推荐：使用静态数组
    static uint8_t static_buf[64];  // 静态分配，大小固定，无碎片化

    cout << "全局计数器地址：" << &global_counter << endl;
    cout << "局部变量值：" << (int)local_var << endl;
    cout << "静态缓冲区大小：" << sizeof(static_buf) << " 字节" << endl;

    // 演示内存节省技巧
    cout << "\n--- 内存节省技巧 ---" << endl;
    cout << "uint8_t（1字节）vs int（4字节）：节省 3 字节" << endl;
    cout << "在 20KB RAM 中，这很重要！" << endl;
}


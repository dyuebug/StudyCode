fn part2_basic_operations() {
    println!("\n============================================================");
    println!("第二部分：基础操作实践");
    println!("============================================================");

    // --------------------------------------------
    // 2.1 示例1：字符串切片基础
    // --------------------------------------------

    println!("\n2.1 示例1：字符串切片基础");
    println!("------------------------------------------------------------");

    // 创建一个String
    let s = String::from("hello world");

    // 创建字符串切片
    // &s[0..5] 表示从索引0到5（不包括5）
    let hello = &s[0..5];  // "hello"
    let world = &s[6..11]; // "world"

    println!("原字符串: {}", s);
    println!("切片1: {}", hello);
    println!("切片2: {}", world);

    // 切片的简写形式
    let s = String::from("hello");

    let slice1 = &s[0..2];  // "he"
    let slice2 = &s[..2];   // 等同于 &s[0..2]
    let slice3 = &s[3..];   // "lo"，从索引3到末尾
    let slice4 = &s[..];    // "hello"，整个字符串

    println!("\n切片简写形式:");
    println!("slice1: {}", slice1);
    println!("slice2: {}", slice2);
    println!("slice3: {}", slice3);
    println!("slice4: {}", slice4);

    // --------------------------------------------
    // 2.2 示例2：字符串字面量是切片
    // --------------------------------------------

    println!("\n2.2 示例2：字符串字面量是切片");
    println!("------------------------------------------------------------");

    // 字符串字面量的类型是 &str
    let s: &str = "Hello, world!";

    // 字符串字面量是不可变的
    // 它们存储在程序的二进制文件中
    println!("字符串字面量: {}", s);
    println!("类型: &str");

    // --------------------------------------------
    // 2.3 示例3：数组切片
    // --------------------------------------------

    println!("\n2.3 示例3：数组切片");
    println!("------------------------------------------------------------");

    // 创建一个数组
    let a = [1, 2, 3, 4, 5];

    // 创建数组切片
    let slice = &a[1..3];  // [2, 3]

    println!("原数组: {:?}", a);
    println!("切片: {:?}", slice);
    println!("切片长度: {}", slice.len());

    // 遍历切片
    print!("切片元素: ");
    for element in slice {
        print!("{} ", element);
    }
    println!();

    // --------------------------------------------
    // 2.4 示例4：函数参数使用切片
    // --------------------------------------------

    println!("\n2.4 示例4：函数参数使用切片");
    println!("------------------------------------------------------------");

    let s = String::from("hello world");

    // 传递 String 的切片
    let word = first_word(&s);
    println!("第一个单词: ", word);

    // 也可以传递字符串字面量
    let word = first_word("hello rust");
    println!("第一个单词: {}", word);

    // --------------------------------------------
    // 2.5 示例5：可变切片
    // --------------------------------------------

    println!("\n2.5 示例5：可变切片");
    println!("------------------------------------------------------------");

    // 创建可变数组
    let mut a = [1, 2, 3, 4, 5];

    // 创建可变切片
    let slice = &mut a[1..4];

    // 通过可变切片修改元素
    slice[0] = 10;
    slice[1] = 20;

    println!("修改后的数组: {:?}", a);  // [1, 10, 20, 4, 5]
}

// 辅助函数：查找第一个单词
// 参数：&str 字符串切片
// 返回：&str 第一个单词的切片
fn first_word(s: &str) -> &str {
    // 将字符串转换为字节数组
    let bytes = s.as_bytes();

    // 遍历字节数组，查找空格
    for (i, &item) in bytes.iter().enumerate() {
        if item == b' ' {  // b' ' 是空格的字节表示
            return &s[0..i];  // 返回第一个单词
        }
    }

    // 如果没有空格，返回整个字符串
    &s[..]
}


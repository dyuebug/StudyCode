/*
==============================================
🔍 深入理解：切片的内存布局（选学）
==============================================

如果你想知道"为什么"，可以阅读这部分。
如果觉得难，可以跳过，不影响后续学习。

【切片的内存表示】

切片在内存中是一个"胖指针"（fat pointer），包含两个字段：
1. 指向数据的指针
2. 切片的长度

示例：
```rust
let s = String::from("hello world");
let hello = &s[0..5];
```

内存布局：
```
栈内存：
+--------+
| s      | -> String { ptr, len, capacity }
+--------+
| hello  | -> &str { ptr, len }
+--------+

堆内存：
+---+---+---+---+---+---+---+---+---+---+---+
| h | e | l | l | o |   | w | o | r | l | d |
+---+---+---+---+---+---+---+---+---+---+---+
  ^                   ^
  |                   |
hello.ptr         s.ptr
hello.len = 5     s.len = 11
```

【为什么切片需要长度信息？】

- C语言的字符串以 '\0' 结尾，不需要长度
- Rust的字符串可以包含 '\0'，需要显式长度
- 切片可以引用数组的任意部分，必须知道长度

【切片 vs 指针】

- C/C++指针：只有地址，不知道长度，不安全
- Rust切片：有地址和长度，编译时检查，安全

==============================================
*/


fn part2_basic_operations() {
    println!("\n============================================================");
    println!("第二部分：基础操作实践");
    println!("============================================================");

    // --------------------------------------------
    // 2.1 示例1：不可变引用
    // --------------------------------------------

    println!("\n2.1 示例1：不可变引用");
    println!("------------------------------------------------------------");

    // 创建一个String
    let s1 = String::from("hello");

    // 创建不可变引用：使用 & 符号
    // &s1 表示"借用s1的值"
    let len = calculate_length(&s1);

    // s1仍然有效，因为我们只是借用了它
    println!("字符串 '{}' 的长度是 {}", s1, len);

    // --------------------------------------------
    // 2.2 示例2：多个不可变引用
    // --------------------------------------------

    println!("\n2.2 示例2：多个不可变引用");
    println!("------------------------------------------------------------");

    let s = String::from("hello");

    // 可以同时有多个不可变引用
    let r1 = &s;  // 第一个不可变引用
    let r2 = &s;  // 第二个不可变引用
    let r3 = &s;  // 第三个不可变引用

    // 所有引用都可以读取数据
    println!("r1: {}, r2: {}, r3: {}", r1, r2, r3);

    // s仍然有效
    println!("原始字符串: {}", s);

    // --------------------------------------------
    // 2.3 示例3：可变引用
    // --------------------------------------------

    println!("\n2.3 示例3：可变引用");
    println!("------------------------------------------------------------");

    // 必须声明为可变变量
    let mut s = String::from("hello");

    // 创建可变引用：使用 &mut
    // &mut s 表示"可变地借用s"
    change(&mut s);

    // s的值已经被修改
    println!("修改后的字符串: {}", s);

    // --------------------------------------------
    // 2.4 示例4：引用的作用域
    // --------------------------------------------

    println!("\n2.4 示例4：引用的作用域");
    println!("------------------------------------------------------------");

    let mut s = String::from("hello");

    {
        // r1在这个作用域内有效
        let r1 = &mut s;
        r1.push_str(", world");
        println!("r1: {}", r1);
    } // r1离开作用域，借用结束

    // 现在可以再次借用s
    let r2 = &mut s;
    r2.push_str("!");
    println!("r2: {}", r2);
}

// 辅助函数：计算字符串长度
// 参数：&String 表示接受String的不可变引用
// 返回：usize 类型的长度
fn calculate_length(s: &String) -> usize {
    // s是引用，不拥有String
    // 所以函数结束时不会释放String
    s.len()
} // s离开作用域，但因为它不拥有值，所以什么也不会发生

// 辅助函数：修改字符串
// 参数：&mut String 表示接受String的可变引用
fn change(s: &mut String) {
    // 可以通过可变引用修改值
    s.push_str(", world");
}

/*
==============================================
🔍 深入理解：借用检查器的工作原理（选学）
==============================================

【借用检查器如何工作】

编译器会分析每个引用的生命周期：

```rust
let mut s = String::from("hello");

let r1 = &s;      // r1的生命周期开始
let r2 = &s;      // r2的生命周期开始

println!("{} {}", r1, r2);
// r1和r2的生命周期在这里结束（最后一次使用）

let r3 = &mut s;  // 现在可以创建可变引用
```

关键点：
- 引用的生命周期从创建开始，到最后一次使用结束
- 编译器会检查是否有重叠的可变引用和不可变引用
- 这被称为"非词法作用域生命周期"（NLL）

【内存布局】

```
栈内存：
+--------+
| s      | -> 指向堆内存的String
+--------+
| r1     | -> 指向s（不可变引用）
+--------+
| r2     | -> 指向s（不可变引用）
+--------+

堆内存：
+---+---+---+---+---+
| h | e | l | l | o |
+---+---+---+---+---+
```

引用只是指针，不拥有数据。

==============================================
*/


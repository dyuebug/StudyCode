/*
【核心概念】引用和借用

是什么？
- 引用：指向值的指针，但不拥有该值
- 借用：通过引用访问值，而不获取所有权

为什么需要？
- 避免所有权转移导致的值失效
- 允许多个地方访问同一个值
- 提高代码的灵活性和效率

核心特点：
- 引用不拥有值，不会释放值
- 借用规则在编译时检查
- 防止数据竞争和悬垂引用

Rust特色：
- 借用检查器（Borrow Checker）在编译时保证安全
- 同一时间只能有一个可变引用，或多个不可变引用
- 引用必须始终有效
*/


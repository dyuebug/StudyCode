/*
【核心概念】函数与闭包

是什么？
- 函数（fn）：命名的、可重用的代码块
- 闭包（closure）：可以捕获环境变量的匿名函数

为什么需要？
- 函数：复用代码，分离逻辑
- 闭包：作为参数传递行为，简化代码

核心特点：
- Rust 函数参数和返回值必须声明类型
- 函数体是语句和表达式的序列
- 最后一个表达式（不加分号）自动作为返回值
- 闭包可以自动推断参数类型

Rust特色：
- 表达式 vs 语句：加分号是语句（无返回值），不加是表达式（有返回值）
- 闭包根据捕获方式分三种：Fn、FnMut、FnOnce
*/

// ============================================
// 第一部分：核心概念详解 ⭐⭐⭐⭐⭐
// ============================================

fn main() {
    println!("============================================================");
    println!("第一部分：函数基础");
    println!("============================================================");

    // --------------------------------------------
    // 1.1 函数定义和调用
    // --------------------------------------------

    // 无参数无返回值
    greet();

    // 有参数
    print_sum(3, 5);

    // 有返回值
    let result = add(10, 20);
    println!("add(10, 20) = {}", result);

    // --------------------------------------------
    // 1.2 表达式作为返回值（Rust特色！）
    // --------------------------------------------

    // 函数体最后一个表达式（不加分号）即为返回值
    // 这与 return 等价，但更符合 Rust 风格
    let x = square(5);
    println!("5的平方 = {}", x);

    // --------------------------------------------
    // 1.3 多返回值（通过元组）
    // --------------------------------------------

    let (min, max) = min_max(&[3, 1, 4, 1, 5, 9, 2, 6]);
    println!("最小值={}, 最大值={}", min, max);

    println!("\n============================================================");
    println!("第二部分：闭包");
    println!("============================================================");

    // --------------------------------------------
    // 2.1 基本闭包语法
    // --------------------------------------------

    // 闭包语法：|参数| 表达式  或  |参数| { 代码块 }
    let add_one = |x| x + 1;           // 类型自动推断
    let add_two = |x: i32| -> i32 { x + 2 }; // 显式类型

    println!("add_one(5) = {}", add_one(5));
    println!("add_two(5) = {}", add_two(5));

    // --------------------------------------------
    // 2.2 闭包捕获环境变量（Rust特色！）
    // --------------------------------------------

    let threshold = 10; // 环境变量

    // 闭包捕获了外部变量 threshold
    let is_big = |x| x > threshold; // 借用捕获

    println!("20 > {} ? {}", threshold, is_big(20));
    println!("5 > {} ? {}", threshold, is_big(5));

    // --------------------------------------------
    // 2.3 闭包作为函数参数
    // --------------------------------------------

    let numbers = vec![1, 2, 3, 4, 5, 6];

    // filter 接受一个闭包，返回满足条件的元素
    let evens: Vec<i32> = numbers.iter()
        .filter(|&&x| x % 2 == 0)  // 保留偶数
        .cloned()
        .collect();
    println!("偶数: {:?}", evens);

    // map 接受一个闭包，对每个元素进行变换
    let doubled: Vec<i32> = numbers.iter()
        .map(|&x| x * 2)            // 每个元素乘2
        .collect();
    println!("乘2: {:?}", doubled);

    // --------------------------------------------
    // 2.4 move 闭包（获取所有权）
    // --------------------------------------------

    let name = String::from("Alice");

    // move 关键字强制闭包获取所有权（常用于线程）
    let greet_fn = move || println!("Hello, {}!", name);

    greet_fn();
    // println!("{}", name); // 错误！name 已被 move 进闭包

    println!("\n============================================================");
    println!("第三部分：函数指针与高阶函数");
    println!("============================================================");

    // 函数可以作为参数传递
    let result = apply(double, 5); // double 是函数名
    println!("apply(double, 5) = {}", result);

    // 闭包也可以传递
    let result = apply(|x| x * x, 5);
    println!("apply(平方, 5) = {}", result);
}

// ============================================
// 辅助函数
// ============================================

fn greet() {
    println!("Hello from function!");
}

fn print_sum(x: i32, y: i32) {
    println!("{} + {} = {}", x, y, x + y);
}

// 有返回值：-> 类型
fn add(x: i32, y: i32) -> i32 {
    x + y  // 不加分号 = 表达式 = 返回值
}

fn square(x: i32) -> i32 {
    x * x  // 等价于 return x * x;
}

// 返回元组实现多返回值
fn min_max(arr: &[i32]) -> (i32, i32) {
    let mut min = arr[0];
    let mut max = arr[0];
    for &x in arr {
        if x < min { min = x; }
        if x > max { max = x; }
    }
    (min, max) // 返回元组
}

// 接受函数指针作为参数
// fn(i32) -> i32 是函数指针类型
fn apply(f: fn(i32) -> i32, x: i32) -> i32 {
    f(x)
}

fn double(x: i32) -> i32 {
    x * 2
}


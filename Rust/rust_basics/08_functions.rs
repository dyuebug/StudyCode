/*
❌ 错误1：语句误用为表达式（多加了分号）
```rust
fn add(x: i32, y: i32) -> i32 {
    x + y;  // 错误！加了分号变成语句，返回 ()
}
```
编译器错误：expected `i32`, found `()`
✅ 正确：去掉分号：x + y

────────────────────────────────────

❌ 错误2：闭包捕获后原变量被移动
```rust
let s = String::from("hello");
let f = move || println!("{}", s);
println!("{}", s); // 错误！s 已被 move 进闭包
```
编译器错误：value borrowed here after move
✅ 正确：在闭包中使用引用，或在 move 后不再使用原变量

────────────────────────────────────

❌ 错误3：闭包类型推断后不能改变参数类型
```rust
let f = |x| x + 1;
f(5);      // 推断 x 为 i32
f(5.0);    // 错误！类型已固定为 i32
```
编译器错误：mismatched types
✅ 正确：第一次调用后类型固定，需要另一个闭包处理不同类型

────────────────────────────────────

❌ 错误4：函数参数缺少类型注解
```rust
fn add(x, y) -> i32 { x + y } // 错误！
```
编译器错误：expected one of `:`, ...
✅ 正确：fn add(x: i32, y: i32) -> i32 { x + y }

────────────────────────────────────

❌ 错误5：闭包捕获可变引用冲突
```rust
let mut v = vec![1, 2, 3];
let push = || v.push(4);  // 可变借用
println!("{:?}", v);       // 错误！v 已被可变借用
push();
```
编译器错误：cannot borrow `v` as immutable because it is also borrowed as mutable
✅ 正确：先调用闭包，再使用 v
*/


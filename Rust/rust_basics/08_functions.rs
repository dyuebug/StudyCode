/*
【函数定义语法】

fn 函数名(参数名: 类型, ...) -> 返回类型 {
    // 函数体
    表达式  // 最后一个表达式（不加分号）作为返回值
}

【闭包语法】

|参数| 表达式                      // 单表达式，类型推断
|参数: 类型| -> 类型 { 代码块 }   // 完整语法
move |参数| 表达式                 // 获取所有权

【常用高阶函数】

.map(|x| ...)      — 对每个元素变换
.filter(|x| ...)   — 过滤满足条件的元素
.fold(init, |acc, x| ...) — 累积计算（相当于 reduce）
.for_each(|x| ...) — 对每个元素执行操作（无返回值）
.any(|x| ...)      — 是否存在满足条件的元素
.all(|x| ...)      — 是否所有元素都满足条件
*/


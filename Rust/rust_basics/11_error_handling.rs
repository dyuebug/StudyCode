/*
【宏：panic!】

语法：panic!("错误信息")
作用：立即终止程序，打印错误信息和调用栈。
返回：永不返回（程序崩溃）。
示例：
```rust
panic!("出大事了：{}", reason);
```

────────────────────────────────────

【方法：Result::unwrap()】

语法：result.unwrap()
作用：Ok(v) → 返回 v；Err(e) → panic。
返回：成功值 T。
所有权：消耗 self（拿走 Result 的所有权）。
示例：
```rust
let n: i32 = "42".parse().unwrap();
```

────────────────────────────────────

【方法：Result::expect()】

语法：result.expect("自定义 panic 信息")
作用：和 unwrap 相同，但 panic 时显示你提供的信息。
返回：成功值 T。
示例：
```rust
let n: i32 = "42".parse().expect("配置项必须是整数");
```

────────────────────────────────────

【运算符：?】

语法：表达式?
作用：Ok(v) → 取出 v；Err(e) → return Err(e)。
要求：所在函数返回 Result 或 Option。
示例：
```rust
let x = "42".parse::<i32>()?;
```

────────────────────────────────────

【方法：Result::map_err()】

语法：result.map_err(|e| 新错误)
作用：把 Err 里的错误转换成另一种类型，Ok 不变。
返回：Result<T, 新错误类型>。
示例：
```rust
let x = "42".parse::<i32>().map_err(|e| e.to_string())?;
```
*/


// 引入标准库的解析错误类型，后面会用到
use std::num::ParseIntError;

fn main() {
    println!("============================================================");
    println!("第二部分：错误处理基础操作实践");
    println!("============================================================");

    // --------------------------------------------
    // 2.1 panic! —— 不可恢复错误
    // --------------------------------------------

    println!("\n2.1 panic! 演示（已注释，避免程序崩溃）");
    println!("------------------------------------------------------------");

    // panic! 会立即终止程序并打印错误信息。
    // 下面这行如果取消注释，程序会在这里崩溃，后面的代码都不执行。
    // panic!("这是一个主动触发的崩溃！");

    // 数组越界也会 panic（Rust 在运行时检查边界，保证内存安全）
    let v = vec![1, 2, 3]; // vec! 宏创建动态数组 Vec<i32>，元素为 1,2,3
    // let x = v[99];      // ❌ 越界！会 panic: index out of bounds
    println!("数组第一个元素：{}", v[0]); // 正常访问，输出 1

    // --------------------------------------------
    // 2.2 用 match 处理 Result
    // --------------------------------------------

    println!("\n2.2 用 match 处理 Result");
    println!("------------------------------------------------------------");

    // "10" 是合法数字字符串，parse 会成功返回 Ok(10)
    let result1 = parse_number("10");
    // match 穷举 Result 的两种情况：Ok 和 Err
    match result1 {
        Ok(n) => println!("解析成功：{}", n),        // 取出 Ok 里的值 n
        Err(e) => println!("解析失败：{}", e),        // 取出 Err 里的错误 e
    }

    // "abc" 不是数字，parse 会失败返回 Err(...)
    let result2 = parse_number("abc");
    match result2 {
        Ok(n) => println!("解析成功：{}", n),
        Err(e) => println!("解析失败：{}", e),        // 这里会执行
    }

    // --------------------------------------------
    // 2.3 unwrap 与 expect —— 快速取值（慎用！）
    // --------------------------------------------

    println!("\n2.3 unwrap 与 expect");
    println!("------------------------------------------------------------");

    // unwrap()：如果是 Ok 就取出值；如果是 Err 就直接 panic 崩溃。
    let n: i32 = "42".parse().unwrap(); // "42" 能解析，安全取出 42
    println!("unwrap 取值：{}", n);

    // expect()：和 unwrap 一样，但可以自定义 panic 信息（调试更友好）
    let m: i32 = "100".parse().expect("解析整数失败"); // 成功取出 100
    println!("expect 取值：{}", m);

    // 下面两行如果取消注释会 panic（因为 "abc" 解析失败）：
    // let bad: i32 = "abc".parse().unwrap();              // panic，信息很笼统
    // let bad: i32 = "abc".parse().expect("数字无效");     // panic，信息是你写的

    // --------------------------------------------
    // 2.4 ? 运算符 —— 错误传播 ⭐⭐⭐⭐⭐
    // --------------------------------------------

    println!("\n2.4 ? 运算符（错误传播）");
    println!("------------------------------------------------------------");

    // 调用一个内部用了 ? 的函数。它本身也返回 Result，所以也要 match。
    match sum_two_numbers("20", "22") {
        Ok(sum) => println!("两数之和：{}", sum),     // 20+22=42
        Err(e) => println!("计算失败：{}", e),
    }

    // 传入非法字符串，? 会让错误自动向上传播
    match sum_two_numbers("20", "xyz") {
        Ok(sum) => println!("两数之和：{}", sum),
        Err(e) => println!("计算失败：{}", e),         // 这里会执行
    }
}

// --------------------------------------------
// 辅助函数：解析字符串为数字，返回 Result
// --------------------------------------------

// 函数签名说明：
//   - 参数 s: &str（字符串切片，借用，不夺所有权）
//   - 返回 Result<i32, ParseIntError>
//        成功 → Ok(i32)
//        失败 → Err(ParseIntError)（标准库的解析错误类型）
fn parse_number(s: &str) -> Result<i32, ParseIntError> {
    // s.parse() 会尝试把字符串解析成目标类型。
    // 这里通过返回类型 i32 推断出要解析成 i32。
    // parse 本身就返回 Result，所以可以直接返回它。
    s.parse::<i32>()
}

// --------------------------------------------
// 演示 ? 运算符的函数
// --------------------------------------------

// ? 运算符规则：
//   - 如果表达式是 Ok(v)，就取出 v 继续往下执行
//   - 如果表达式是 Err(e)，就立即 return Err(e)（提前返回，把错误甩给调用者）
//   - 要求：所在函数的返回类型必须是 Result（或 Option）
fn sum_two_numbers(a: &str, b: &str) -> Result<i32, ParseIntError> {
    let x = a.parse::<i32>()?; // 解析成功取出值；失败则立即 return Err
    let y = b.parse::<i32>()?; // 同上
    Ok(x + y)                  // 都成功，返回 Ok(和)
}

/*
==============================================
🔍 深入理解：? 运算符到底做了什么？（选学）
==============================================

如果觉得难，可以跳过，不影响后续学习。

? 运算符其实是一个"语法糖"。下面这行：

    let x = a.parse::<i32>()?;

完全等价于这段 match：

    let x = match a.parse::<i32>() {
        Ok(v) => v,                  // 成功：取出值
        Err(e) => return Err(e),     // 失败：立即把错误返回给调用者
    };

所以 ? 帮你省掉了大量重复的 match 代码。这就是为什么真实项目里
到处都是 ?——它让"错误传播"变得极其简洁。

【为什么 ? 只能用在返回 Result 的函数里？】
因为 ? 在失败时要执行 `return Err(e)`。如果函数不返回 Result，
这个 return 就没有意义，编译器会直接报错。

【? 还能用于 Option】
如果函数返回 Option<T>，? 遇到 None 时会 `return None`。
机制完全一样，只是换了枚举。

==============================================
*/


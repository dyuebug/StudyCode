/*
4.1 错误1：在不返回 Result 的函数里用 ?
------------------------------------------------------------

❌ 错误代码：
```rust
fn main() {
    let x = "42".parse::<i32>()?; // ❌ main 默认不返回 Result
}
```

编译器错误信息：
error[E0277]: the `?` operator can only be used in a function that
returns `Result` or `Option`

原因：? 失败时要 `return Err`，但 main 的返回类型是 ()，无法返回 Err。

✅ 正确代码（方式一：改用 match 或 unwrap）：
```rust
fn main() {
    let x: i32 = "42".parse().unwrap();
}
```

✅ 正确代码（方式二：让 main 返回 Result）：
```rust
fn main() -> Result<(), std::num::ParseIntError> {
    let x = "42".parse::<i32>()?;
    Ok(())
}
```

记忆技巧：? 要往哪里"甩"错误，函数就得能"接住"——返回类型必须是 Result/Option。

────────────────────────────────────

4.2 错误2：滥用 unwrap 导致程序崩溃
------------------------------------------------------------

❌ 错误代码：
```rust
let config: i32 = user_input.parse().unwrap(); // 用户随便输入就崩溃
```

原因：unwrap 在 Err 时直接 panic。生产环境的用户输入、文件、网络
都是不可控的，unwrap 等于埋了一颗"随时引爆"的炸弹。

✅ 正确代码：
```rust
match user_input.parse::<i32>() {
    Ok(n) => println!("有效数字：{}", n),
    Err(_) => println!("请输入有效数字"),
}
```

预防措施：unwrap/expect 只在以下场景用：
  - 写示例/原型代码
  - 你100%确定不会失败（且写注释说明为什么）
  - 测试代码

────────────────────────────────────

4.3 错误3：错误类型不匹配
------------------------------------------------------------

❌ 错误代码：
```rust
fn run() -> Result<(), String> {
    let x = "42".parse::<i32>()?; // parse 返回的错误是 ParseIntError
    Ok(())                         // 但函数声明的错误类型是 String，不匹配！
}
```

编译器错误信息：
error[E0277]: `?` couldn't convert the error to `String`

原因：? 传播的错误类型（ParseIntError）必须能转换成函数声明的错误类型（String）。

✅ 正确代码（方式一：错误类型保持一致）：
```rust
fn run() -> Result<(), std::num::ParseIntError> {
    let x = "42".parse::<i32>()?;
    Ok(())
}
```

✅ 正确代码（方式二：用 map_err 手动转换）：
```rust
fn run() -> Result<(), String> {
    let x = "42".parse::<i32>().map_err(|e| e.to_string())?;
    Ok(())
}
```

记忆技巧：? 会尝试用 From trait 自动转换错误类型；转换不了就报错。

────────────────────────────────────

4.4 错误4：忽略 Result 返回值（警告）
------------------------------------------------------------

⚠️ 有问题的代码：
```rust
"abc".parse::<i32>(); // 返回的 Result 被丢弃了，没人处理
```

编译器警告信息：
warning: unused `Result` that must be used

原因：Result 标记了 #[must_use]，丢弃它意味着你可能忽略了一个错误。

✅ 正确做法：用 match / unwrap / ? / let _ = 明确表态你想怎么处理。

────────────────────────────────────

4.5 错误5：混淆 panic 和 Result 的使用场景
------------------------------------------------------------

❌ 思维误区：所有错误都用 panic! 处理。

原因：panic 会终止整个程序。对于"预期内"的失败（文件不存在、
输入非法），应该用 Result 优雅处理，让调用者决定怎么办。

✅ 判断标准：
  - 这个错误"预期内、可处理" → 用 Result
  - 这个错误"是 bug、不该发生" → 用 panic!（或 unwrap）

记忆口诀：能恢复的用 Result，恢复不了的才 panic。
*/


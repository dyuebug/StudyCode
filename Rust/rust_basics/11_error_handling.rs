/*
【概念1：两种错误类型】

1. 不可恢复错误（panic!）
   - 程序遇到了无法继续的严重问题，直接崩溃退出。
   - 例子：数组越界访问、主动调用 panic!
   - 适用场景：bug、不应该发生的情况、原型/示例代码。

2. 可恢复错误（Result<T, E>）
   - 错误是"预期之内"的，程序可以优雅地处理它。
   - 例子：打开文件失败（文件可能不存在）、解析字符串失败。
   - 适用场景：绝大多数真实业务逻辑。

────────────────────────────────────

【概念2：Result<T, E> 枚举】⭐⭐⭐⭐⭐

Result 是 Rust 标准库定义的枚举（还记得第10天学的枚举吗？）：

    enum Result<T, E> {
        Ok(T),    // 成功，携带成功的值（类型 T）
        Err(E),   // 失败，携带错误信息（类型 E）
    }

- T 是成功时返回值的类型（泛型，明天会细讲）
- E 是失败时错误的类型
- 任何"可能失败"的操作都返回 Result，强制你处理两种情况。

对比第10天学的 Option<T>：
    Option<T> = Some(T) / None      → "有值 或 没值"
    Result<T, E> = Ok(T) / Err(E)   → "成功 或 失败（且带原因）"

Option 表达"有没有"，Result 表达"成没成 + 为什么没成"。

────────────────────────────────────

【概念3：处理 Result 的几种方式】

1. match 穷举匹配（最原始、最清晰）
2. unwrap() / expect()（快速取值，失败就 panic，慎用）
3. ? 运算符（错误传播，最常用）⭐⭐⭐⭐⭐

下面的代码会逐一演示。
*/


/*
【核心概念】简要说明

是什么？
- 错误处理是程序应对"意外情况"的机制（如文件不存在、网络断开、除以零）。
- Rust 没有其他语言的 try/catch 异常机制，而是把错误当作"普通的值"来处理。

为什么需要？
- 程序运行时总会遇到失败：读不到文件、解析不了数字、数组越界……
- 如果不处理，程序可能崩溃或产生错误结果。Rust 强制你"显式"处理错误。

核心特点？
- Rust 把错误分成两大类：
  1. 不可恢复错误（unrecoverable）→ 用 panic! 直接终止程序
  2. 可恢复错误（recoverable）   → 用 Result<T, E> 返回，让调用者决定怎么办

Rust特色？
- 没有 null、没有异常（exception）。错误是类型系统的一部分，编译器强制你处理。
- 这意味着：你不可能"忘记"处理一个错误——不处理就编译不过。
*/


/*
❌ 错误1：if 条件不是 bool 类型
```rust
let n = 3;
if n {  // 错误！Rust不会自动把数字转为bool
    println!("n不为零");
}
```
编译器错误：expected `bool`, found integer
✅ 正确：if n != 0 { ... }

────────────────────────────────────

❌ 错误2：if 表达式两个分支类型不同
```rust
let v = if true { 5 } else { "hello" }; // 错误！
```
编译器错误：`if` and `else` have incompatible types
✅ 正确：两个分支必须返回相同类型

────────────────────────────────────

❌ 错误3：忘记 loop 中的 break
```rust
loop {
    println!("无限循环！");
    // 没有 break，程序永远不会停止
}
```
✅ 正确：确保 loop 中有 break 退出条件

────────────────────────────────────

❌ 错误4：while 循环修改集合长度导致索引错误
```rust
let a = [1, 2, 3, 4, 5];
let mut i = 0;
while i < 5 {
    println!("{}", a[i]); // 如果 a 的长度变化，可能 panic
    i += 1;
}
```
✅ 正确：用 for 遍历，编译器保证安全
```rust
for element in a { println!("{}", element); }
```

────────────────────────────────────

❌ 错误5：在 for 循环中修改正在遍历的集合
```rust
let mut v = vec![1, 2, 3];
for x in &v {
    v.push(*x); // 错误！不能同时借用和修改
}
```
编译器错误：cannot borrow `v` as mutable because it is also borrowed as immutable
✅ 正确：先收集要添加的元素，循环后再添加
*/


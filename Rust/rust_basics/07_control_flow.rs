/*
【范围语法】

语法：起始..结束（左闭右开）/ 起始..=结束（闭区间）
示例：
  1..5  → 1, 2, 3, 4
  1..=5 → 1, 2, 3, 4, 5

【常用迭代器方法】

.rev()        — 反向遍历
.enumerate()  — 同时获取索引和值，返回 (index, value)
.iter()       — 获取不可变引用的迭代器
.iter_mut()   — 获取可变引用的迭代器
.into_iter()  — 获取所有权的迭代器（消耗集合）
*/


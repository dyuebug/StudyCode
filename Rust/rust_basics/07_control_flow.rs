/*
【核心概念】控制流

是什么？
- 控制程序执行顺序的语句
- 包括：if/else、loop、while、for

为什么需要？
- 根据条件执行不同代码
- 重复执行某段代码

核心特点：
- if 是表达式，可以返回值
- loop 是无限循环，可以用 break 返回值
- for 是最常用的循环方式

Rust特色：
- if/else 可以作为表达式赋值给变量
- loop 可以通过 break value 返回值
- for 遍历迭代器，没有 C 风格的三段式 for
*/

// ============================================
// 第一部分：核心概念详解 ⭐⭐⭐⭐⭐
// ============================================

fn main() {
    println!("============================================================");
    println!("第一部分：if/else 条件判断");
    println!("============================================================");

    // --------------------------------------------
    // 1.1 基本 if/else
    // --------------------------------------------

    let number = 7;

    // if 条件不需要括号，但条件必须是 bool 类型
    if number < 5 {
        println!("条件为真");
    } else {
        println!("条件为假");
    }

    // --------------------------------------------
    // 1.2 if 作为表达式（Rust特色！）
    // --------------------------------------------

    // if 是表达式，可以直接赋值给变量
    // 两个分支的返回类型必须相同
    let condition = true;
    let value = if condition { 5 } else { 6 }; // value = 5
    println!("if表达式的值: {}", value);

    // --------------------------------------------
    // 1.3 else if 多条件判断
    // --------------------------------------------

    let n = 6;
    if n % 4 == 0 {
        println!("{} 能被4整除", n);
    } else if n % 3 == 0 {
        println!("{} 能被3整除", n);
    } else if n % 2 == 0 {
        println!("{} 能被2整除", n);
    } else {
        println!("{} 不能被4、3、2整除", n);
    }

    println!("\n============================================================");
    println!("第二部分：loop 无限循环");
    println!("============================================================");

    // --------------------------------------------
    // 2.1 基本 loop
    // --------------------------------------------

    let mut counter = 0;
    loop {
        counter += 1;
        if counter == 3 {
            break; // 退出循环
        }
    }
    println!("counter = {}", counter);

    // --------------------------------------------
    // 2.2 loop 返回值（Rust特色！）
    // --------------------------------------------

    // break 后面可以跟值，作为整个 loop 表达式的返回值
    let mut counter = 0;
    let result = loop {
        counter += 1;
        if counter == 10 {
            break counter * 2; // 返回 20
        }
    };
    println!("loop返回值: {}", result); // 20

    // --------------------------------------------
    // 2.3 循环标签（嵌套循环时指定 break 的目标）
    // --------------------------------------------

    let mut count = 0;
    'outer: loop {           // 'outer 是循环标签
        let mut inner = 0;
        loop {
            if inner == 2 {
                break;       // 退出内层循环
            }
            if count == 2 {
                break 'outer; // 退出外层循环
            }
            inner += 1;
        }
        count += 1;
    }
    println!("count = {}", count);

    println!("\n============================================================");
    println!("第三部分：while 条件循环");
    println!("============================================================");

    let mut n = 3;
    while n != 0 {
        println!("{}!", n);
        n -= 1;
    }
    println!("发射！");

    println!("\n============================================================");
    println!("第四部分：for 遍历");
    println!("============================================================");

    // --------------------------------------------
    // 4.1 遍历数组
    // --------------------------------------------

    let a = [10, 20, 30, 40, 50];

    // for 遍历迭代器，比 while+索引更安全、更简洁
    for element in a {
        print!("{} ", element);
    }
    println!();

    // --------------------------------------------
    // 4.2 遍历范围 Range
    // --------------------------------------------

    // (1..4) 是左闭右开：1, 2, 3
    for i in 1..4 {
        println!("i = {}", i);
    }

    // (1..=4) 是闭区间：1, 2, 3, 4
    for i in 1..=4 {
        print!("{} ", i);
    }
    println!();

    // --------------------------------------------
    // 4.3 rev() 反向遍历
    // --------------------------------------------

    for i in (1..4).rev() { // 3, 2, 1
        print!("{} ", i);
    }
    println!();

    // --------------------------------------------
    // 4.4 enumerate() 同时获取索引和值
    // --------------------------------------------

    let fruits = ["苹果", "香蕉", "橙子"];
    for (index, value) in fruits.iter().enumerate() {
        println!("{}. {}", index, value);
    }
}


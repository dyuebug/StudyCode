fn part2_basic_usage() {
    println!("\n============================================================");
    println!("第二部分：基础操作实践");
    println!("============================================================");

    // --------------------------------------------
    // 2.1 捕获环境：不可变借用
    // --------------------------------------------

    println!("\n2.1 捕获环境：不可变借用");
    println!("------------------------------------------------------------");

    /*
    【不可变借用捕获】

    默认行为：
    - 闭包捕获环境变量的不可变引用（&T）
    - 可以读取环境变量
    - 不能修改环境变量
    - 环境变量在闭包存在期间不能被修改

    特点：
    - 最安全的捕获方式
    - 可以有多个闭包同时捕获
    - 闭包实现 Fn trait
    */

    let x = 4;
    // 闭包捕获 x 的不可变引用
    let equal_to_x = |z| z == x;
    // 等价于：let equal_to_x = |z| z == &x;

    println!("x = {}", x); // x 仍然可读

    let y = 4;
    println!("equal_to_x(y) = {}", equal_to_x(y)); // true

    // 示例2：捕获多个变量
    let list = vec![1, 2, 3];
    let only_borrows = || println!("从闭包中访问: {:?}", list);

    println!("调用闭包前: {:?}", list);
    only_borrows();
    println!("调用闭包后: {:?}", list);

    println!("→ 默认捕获不可变借用，安全且灵活");

    // --------------------------------------------
    // 2.2 捕获环境：可变借用
    // --------------------------------------------

    println!("\n2.2 捕获环境：可变借用");
    println!("------------------------------------------------------------");

    /*
    【可变借用捕获】

    当闭包修改环境变量时：
    - 闭包捕获环境变量的可变引用（&mut T）
    - 可以修改环境变量
    - 环境变量在闭包存在期间不能被其他代码访问
    - 闭包实现 FnMut trait

    注意：
    - 闭包本身需要是 mut 的
    - 同一时间只能有一个可变借用
    */

    let mut list = vec![1, 2, 3];
    println!("修改前: {:?}", list);

    // 闭包捕获 list 的可变引用
    let mut borrows_mutably = || list.push(7);
    // 注意：闭包声明为 mut

    borrows_mutably(); // 修改 list
    println!("修改后: {:?}", list); // [1, 2, 3, 7]

    // 示例2：多次修改
    let mut count = 0;
    let mut increment = || {
        count += 1;
        println!("count = {}", count);
    };

    increment(); // count = 1
    increment(); // count = 2
    increment(); // count = 3

    println!("最终 count = {}", count); // 3

    println!("→ 可变借用允许闭包修改环境变量");

    // --------------------------------------------
    // 2.3 捕获环境：获取所有权（move）
    // --------------------------------------------

    println!("\n2.3 捕获环境：获取所有权（move）");
    println!("------------------------------------------------------------");

    /*
    【所有权捕获 (move)】

    使用 move 关键字：
    - 强制闭包获取环境变量的所有权
    - 环境变量被移动到闭包中
    - 原环境不能再使用这些变量
    - 闭包实现 FnOnce trait（或 Fn/FnMut，取决于闭包内部如何使用）

    使用场景：
    - 闭包在新线程中执行
    - 闭包生命周期超过环境变量
    - 需要明确获取所有权

    对 Copy 类型：
    - move 复制值（如 i32）
    - 原变量仍然可用

    对非 Copy 类型：
    - move 移动所有权（如 Vec、String）
    - 原变量不再可用
    */

    // 示例1：Copy 类型
    let x = 1;
    let copy_closure = move || println!("move 后的 x: {}", x);
    copy_closure();
    println!("x 仍然可用: {}", x); // Copy 类型，原值仍可用

    // 示例2：非 Copy 类型
    let list = vec![1, 2, 3];
    println!("move 前: {:?}", list);

    let move_closure = move || println!("move 后: {:?}", list);
    // list 的所有权移动到闭包

    move_closure();
    // println!("{:?}", list); // ❌ 编译错误：list 已被移动

    // 示例3：多线程中的 move
    let data = vec![1, 2, 3];
    let handle = thread::spawn(move || {
        // move 确保 data 的所有权移动到新线程
        println!("线程中: {:?}", data);
    });
    handle.join().unwrap();
    // data 不再可用

    println!("→ move 关键字让闭包获取所有权，常用于多线程");
}


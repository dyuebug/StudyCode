/*
【核心概念】闭包 (Closures)

是什么？
- 闭包是可以捕获其环境的匿名函数
- 语法：|param1, param2| expression 或 |param| { statements }
- 类似其他语言的 lambda、匿名函数

为什么需要？
- 代码简洁：无需定义独立函数
- 环境捕获：可以使用外部变量
- 函数式编程：与迭代器配合使用

核心特点？
- 类型推断：通常可以省略参数和返回值类型
- 环境捕获：三种方式（不可变借用、可变借用、所有权）
- 唯一类型：每个闭包都有唯一的匿名类型

Rust特色？
- 零成本抽象：闭包性能和手写函数一样
- 内存安全：借用检查器保证安全
- 灵活性：Fn、FnMut、FnOnce 三个 trait 提供不同权限
*/

use std::thread;

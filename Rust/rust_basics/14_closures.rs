fn part1_concepts() {
    println!("============================================================");
    println!("第一部分：核心概念详解");
    println!("============================================================");

    // --------------------------------------------
    // 1.1 什么是闭包？
    // --------------------------------------------

    println!("\n1.1 什么是闭包？");
    println!("------------------------------------------------------------");

    /*
    【闭包 Closure】

    是什么？
    - 匿名函数，可以保存在变量中或作为参数传递
    - 可以捕获定义时环境中的变量
    - 语法简洁，通常用于短小的逻辑

    语法形式：
    - 简单表达式：|param| expression
    - 多个参数：|x, y| x + y
    - 代码块：|x| { let y = x + 1; y * 2 }
    - 类型标注：|x: i32| -> i32 { x + 1 }

    与函数的区别：
    - 闭包可以捕获环境，函数不能
    - 闭包有类型推断，函数必须显式标注
    - 每个闭包都有唯一的匿名类型

    Rust特色：
    - 零成本抽象：编译器内联优化后和手写函数性能一样
    - 类型安全：借用检查器保证环境捕获的安全性
    */

    // 示例1：简单闭包
    let add_one = |x| x + 1;
    // |x|：参数
    // x + 1：表达式
    // 类型推断：从使用推断出 x 是 i32
    println!("add_one(5) = {}", add_one(5)); // 6

    // 示例2：多参数闭包
    let add = |x, y| x + y;
    println!("add(2, 3) = {}", add(2, 3)); // 5

    // 示例3：代码块闭包
    let multiply = |x| {
        let result = x * 2;
        println!("计算中: {} * 2", x);
        result // 返回值
    };
    println!("multiply(4) = {}", multiply(4)); // 8

    println!("→ 闭包是匿名函数，语法简洁，可以捕获环境");

    // --------------------------------------------
    // 1.2 闭包 vs 函数
    // --------------------------------------------

    println!("\n1.2 闭包 vs 函数");
    println!("------------------------------------------------------------");

    /*
    【函数】
    - 必须显式标注参数和返回值类型
    - 不能捕获环境
    - 可以定义在任何地方（全局、模块、impl块）

    【闭包】
    - 通常省略类型标注（类型推断）
    - 可以捕获环境
    - 通常定义在局部作用域

    何时用函数？
    - 不需要捕获环境
    - 需要复用的通用逻辑
    - 需要公开的 API

    何时用闭包？
    - 需要捕获环境
    - 短小的一次性逻辑
    - 作为高阶函数的参数（如 map、filter）
    */

    // 函数版本
    fn function_add_one(x: i32) -> i32 {
        x + 1
    }

    // 闭包版本
    let closure_add_one = |x: i32| -> i32 { x + 1 };

    println!("函数: {}", function_add_one(5));
    println!("闭包: {}", closure_add_one(5));

    println!("→ 函数更通用，闭包更灵活（可捕获环境）");

    // --------------------------------------------
    // 1.3 闭包类型推断
    // --------------------------------------------

    println!("\n1.3 闭包类型推断");
    println!("------------------------------------------------------------");

    /*
    【类型推断】

    闭包的类型从使用中推断：
    - 第一次调用时确定类型
    - 后续调用必须使用相同类型

    可以显式标注类型：
    - |x: i32| -> i32 { x + 1 }
    - 通常不需要，编译器会推断

    每个闭包都有唯一类型：
    - 即使两个闭包逻辑完全相同，类型也不同
    - 编译器为每个闭包生成唯一的匿名类型
    */

    // 类型推断
    let example_closure = |x| x;
    // 第一次调用：确定 x 是 String
    let s = example_closure(String::from("hello"));
    println!("推断为 String: {}", s);

    // ❌ 错误：类型已经确定为 String
    // let n = example_closure(5); // 编译错误

    // 显式类型标注
    let typed_closure = |x: i32| -> i32 { x + 1 };
    println!("显式类型: {}", typed_closure(5));

    println!("→ 闭包有类型推断，但第一次调用后类型就固定了");
}


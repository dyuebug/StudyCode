#!/bin/bash
# ============================================
# 性能对比测试脚本
# 对比同步版本 vs 异步版本
# ============================================

echo "============================================================"
echo "🚀 翻译工具性能对比测试"
echo "============================================================"
echo ""

# 测试数据
texts=("hello" "world" "rust" "async" "tokio")

echo "📝 测试数据："
for text in "${texts[@]}"; do
    echo "  - $text"
done
echo ""

# ============================================
# 测试1：同步版本（顺序执行）
# ============================================

echo "============================================================"
echo "🐢 测试1：同步版本（blocking）"
echo "============================================================"
echo ""

cd translate-cli

echo "⏱️  开始计时..."
start_sync=$(date +%s.%N)

for text in "${texts[@]}"; do
    echo "翻译: $text"
    cargo run --release --quiet -- text "$text" -f en -t zh > /dev/null 2>&1
done

end_sync=$(date +%s.%N)
time_sync=$(echo "$end_sync - $start_sync" | bc)

echo ""
echo "✅ 同步版本完成"
echo "⏱️  总耗时: ${time_sync} 秒"
echo ""

cd ..

# ============================================
# 测试2：异步版本（顺序执行）
# ============================================

echo "============================================================"
echo "⚡ 测试2：异步版本（async - 顺序执行）"
echo "============================================================"
echo ""

cd translate-cli-async

echo "⏱️  开始计时..."
start_async=$(date +%s.%N)

for text in "${texts[@]}"; do
    echo "翻译: $text"
    cargo run --release --quiet -- text "$text" -f en -t zh > /dev/null 2>&1
done

end_async=$(date +%s.%N)
time_async=$(echo "$end_async - $start_async" | bc)

echo ""
echo "✅ 异步版本完成"
echo "⏱️  总耗时: ${time_async} 秒"
echo ""

cd ..

# ============================================
# 结果对比
# ============================================

echo "============================================================"
echo "📊 性能对比结果"
echo "============================================================"
echo ""

echo "同步版本（blocking）：${time_sync} 秒"
echo "异步版本（async）   ：${time_async} 秒"
echo ""

# 计算加速比
speedup=$(echo "scale=2; $time_sync / $time_async" | bc)
echo "⚡ 性能提升：${speedup}x"
echo ""

echo "============================================================"
echo "💡 结论"
echo "============================================================"
echo ""
echo "在顺序执行的场景下，同步版本和异步版本的性能差异不大。"
echo "异步的真正优势在于并发执行多个请求！"
echo ""
echo "下一步：我们将实现批量翻译功能，展示异步的真正威力！🚀"
echo ""
